export type CreateBlockResult =
  | { ok: true }
  | { ok: false; error: string };

/**
 * Create a new block from the wizard input. Returns a result object so the
 * client wizard can surface the failure reason inline instead of crashing
 * the whole page.
 */
export async function createBlock(formData: FormData): Promise<CreateBlockResult> {
  const parsed = createBlockSchema.safeParse({
    archetype: formData.get("archetype"),
    startedOn: formData.get("startedOn"),
    daysPerWeek: formData.get("daysPerWeek"),
    dayIndexOverrides: formData.get("dayIndexOverrides") ?? undefined,
    powerEmphasis: formData.get("powerEmphasis") ?? undefined,
    cardioSource: formData.get("cardioSource") ?? undefined,
    cardioSourceName: formData.get("cardioSourceName") ?? undefined,
    // Focus muscles arrive as repeated `focusMuscles` form fields.
    // Empty getAll() → [] → focusMusclesSchema's `.default([])` path.
    focusMuscles: formData
      .getAll("focusMuscles")
      .map((v) => (typeof v === "string" ? v : ""))
      .filter((v) => v.length > 0),
  });
  if (!parsed.success) {
    return { ok: false, error: parsed.error.issues[0]?.message ?? "Invalid input" };
  }

  // Parse + validate the dayIndexOverrides JSON payload (wizard step 5).
  // Accepts both the legacy `{ days, twoADay }` shape and the post-fix
  // `{ days, twoADay, placements }` shape — Zod's optional `placements`
  // makes the transition safe for any submission that races the deploy.
  let dayIndexOverrides: DayIndexOverrides | null = null;
  if (parsed.data.dayIndexOverrides) {
    try {
      const raw: unknown = JSON.parse(parsed.data.dayIndexOverrides);
      const result = dayIndexOverridesSchema.safeParse(raw);
      if (result.success) {
        dayIndexOverrides = result.data;
      }
    } catch {
      // Bad JSON — silently drop; the block can still be created without overrides.
    }
  }

  const supabase = await createClient();
  const {
    data: { user },
  } = await getAuthUser();
  if (!user) redirect("/login");

  const archetype = ARCHETYPES[parsed.data.archetype];
  if (!archetype) return { ok: false, error: "Unknown archetype" };

  // Look up the user's two-a-day preference + warmup-ladder config + equipment so we pick the right day pool, prepend warmups, and only prescribe movements they can actually do.
  const { data: profile } = await supabase
    .from("profiles")
    .select("allows_two_a_days, warmup_scheme, equipment, barbell_kg, trap_bar_kg, plate_inventory_kg, bw_assessment_completed_at, bodyweight_kg, training_experience")
    .eq("id", user.id)
    .maybeSingle();
  const allowsTwoADays = Boolean(profile?.allows_two_a_days ?? false);
  const warmupScheme = resolveWarmupScheme(profile?.warmup_scheme);
  const equipment = resolveEquipment(profile);
  const experience = resolveDeclaredExperience(profile?.training_experience);

  const minDays = minDaysForArchetype(
    archetype,
    allowsTwoADays,
    equipment.preset === "bodyweight_only",
  );
  if (parsed.data.daysPerWeek < minDays) {
    return {
      ok: false,
      error: `${archetype.name} needs at least ${minDays} training days/week.`,
    };
  }
  const canonicalActiveDays = foldDualMainLifts(
    archetype,
    daysForFrequency(archetype, parsed.data.daysPerWeek, allowsTwoADays),
  );
  // Honour the user's Step-5 arrangement (Mon/Tue/Thu/Sat etc.) when the
  // wizard supplied placements. Without this remap the canonical archetype
  // template order leaks through and overrides whatever the user picked.
  // See `wizard/placements.ts` for the matching strategy + fallbacks.
  const activeDays = applyPlacementsToActiveDays(
    canonicalActiveDays,
    dayIndexOverrides?.placements ?? null,
  );

  const candidateSlugs = allCandidateLiftSlugs(archetype);
  const fixedSlugs = requiredFixedSlugs(archetype);
  const accessorySlugs = allAccessorySlugs();
  const allSlugs = Array.from(new Set([...candidateSlugs, ...fixedSlugs, ...accessorySlugs]));

  const { data: movements, error: mvErr } = await supabase
    .from("movements")
    .select("id, slug, display_name, experience_min, experience_max")
    .in("slug", allSlugs)
    .is("user_id", null);
  if (mvErr) return { ok: false, error: `Movement lookup failed: ${mvErr.message}` };

  const movementBySlug = new Map((movements ?? []).map((m) => [m.slug, m]));

  // Picker catalog — full global catalog with role tags. Loaded only when
  // the archetype has an accessoryProfile so legacy archetypes pay nothing.
  let pickerCatalog: CatalogMovement[] = [];
  if (archetype.accessoryProfile) {
    pickerCatalog = await loadPickerCatalog(supabase);
    if (pickerCatalog.length === 0) {
      return { ok: false, error: "Catalog load failed" };
    }
  }

  const missingFixed = fixedSlugs.filter((s) => !movementBySlug.has(s));
  if (missingFixed.length > 0) {
    return {
      ok: false,
      error: `Catalog is missing required movements: ${missingFixed.join(", ")}. Re-seed movements.`,
    };
  }

  const candidateMovementIds = candidateSlugs
    .map((s) => movementBySlug.get(s)?.id)
    .filter((id): id is string => !!id);

  const { data: tms, error: tmErr } = await supabase
    .from("training_maxes")
    .select("movement_id, updated_at")
    .in("movement_id", candidateMovementIds);

  if (tmErr) return { ok: false, error: `TM lookup failed: ${tmErr.message}` };

  const tmByMovementId = new Map((tms ?? []).map((r) => [r.movement_id, r.updated_at]));

  /**
   * Bodyweight-only / no-TM path. When the user has no training maxes
   * at all (e.g. they picked the bodyweight-only equipment preset and
   * skipped the TM step), the planner can't produce %TM-based main
   * lift items. Build the block anyway with accessories + tendon work
   * only — the picker keys off equipment, so a bodyweight setup yields
   * push-up / pull-up / single-leg / plank variants prescribed via
   * RPE / RIR rather than %TM.
   */
  const hasAnyTm = tmByMovementId.size > 0;

  // ─── Bodyweight Phase 3 — main-lift prescription ─────────────────
  // When the user has no loadable kit AND has populated bw_progress
  // (via the Phase 2 assessment wizard), the planner emits BW main +
  // back-off items per session from the per-family DAG node. Detection
  // matches the plan: `!hasLoadableMainLift(equipment)` AND at least
  // one bw_progress row.
  const bwActive = !hasLoadableMainLift(equipment);
  const bwByFamily = new Map<MovementFamily, BwFamilyContext>();
  if (bwActive) {
    const { data: bwRows } = await supabase
      .from("bw_progress")
      .select("family, current_node_id, clean_rep_history")
      .eq("user_id", user.id);
    const nodeIds = (bwRows ?? [])
      .map((r) => r.current_node_id as string | null)
      .filter((id): id is string => !!id);
    if (nodeIds.length > 0) {
      const { data: nodes } = await supabase
        .from("movement_nodes")
        .select(
          "id, family, node_key, display_name, prerequisites, external_load_capable, isometric_capable, unilateral, default_tempo_seconds, tut_per_rep_seconds, difficulty_anchor, created_at",
        )
        .in("id", nodeIds);
      const nodeById = new Map<string, MovementNode>();
      for (const n of nodes ?? []) {
        // PostgREST returns snake_case columns; hydrate into the typed
        // MovementNode shape used by the matrix helper.
        const row = n as Record<string, unknown>;
        nodeById.set(row.id as string, {
          id: row.id as string,
          family: row.family as MovementFamily,
          nodeKey: row.node_key as string,
          displayName: row.display_name as string,
          prerequisites: (row.prerequisites as string[]) ?? [],
          externalLoadCapable: Boolean(row.external_load_capable),
          isometricCapable: Boolean(row.isometric_capable),
          unilateral: Boolean(row.unilateral),
          defaultTempoSeconds: row.default_tempo_seconds as number,
          tutPerRepSeconds: row.tut_per_rep_seconds as number,
          difficultyAnchor: row.difficulty_anchor as number,
          createdAt: row.created_at as unknown as Date,
        });
      }

      // Resolve a real `movements` row per node so the focus view's
      // per-movement grouping keeps working. We look up by slug ==
      // node_key against the global catalog; nodes without a matching
      // catalog movement borrow whichever movement row the day already
      // resolved to (set later, inside the day loop).
      const bwNodeSlugs = Array.from(
        new Set(Array.from(nodeById.values()).map((n) => n.nodeKey)),
      );
      const { data: bwMovements } = await supabase
        .from("movements")
        .select("id, slug, display_name")
        .in("slug", bwNodeSlugs)
        .is("user_id", null);
      const bwMovementBySlug = new Map(
        (bwMovements ?? []).map((m) => [m.slug as string, m] as const),
      );

      // Phase 4 — fetch DAG children of every current node so we can
      // stamp the "Next:" preview onto each BW prescription item.
      // One round-trip via `overlaps` against the prerequisites
      // array; results filtered to same-family children below.
      const { data: childRowsRaw } = await supabase
        .from("movement_nodes")
        .select(
          "id, family, node_key, display_name, prerequisites, external_load_capable, isometric_capable, unilateral, default_tempo_seconds, tut_per_rep_seconds, difficulty_anchor, created_at",
        )
        .overlaps("prerequisites", nodeIds);
      const childrenByCurrentId = new Map<string, MovementNode[]>();
      for (const r of (childRowsRaw ?? []) as Array<Record<string, unknown>>) {
        const childNode: MovementNode = {
          id: r.id as string,
          family: r.family as MovementFamily,
          nodeKey: r.node_key as string,
          displayName: r.display_name as string,
          prerequisites: (r.prerequisites as string[]) ?? [],
          externalLoadCapable: Boolean(r.external_load_capable),
          isometricCapable: Boolean(r.isometric_capable),
          unilateral: Boolean(r.unilateral),
          defaultTempoSeconds: r.default_tempo_seconds as number,
          tutPerRepSeconds: r.tut_per_rep_seconds as number,
          difficultyAnchor: r.difficulty_anchor as number,
          createdAt: r.created_at as unknown as Date,
        };
        for (const prereq of childNode.prerequisites) {
          if (!nodeIds.includes(prereq)) continue;
          const arr = childrenByCurrentId.get(prereq) ?? [];
          arr.push(childNode);
          childrenByCurrentId.set(prereq, arr);
        }
      }

      for (const row of bwRows ?? []) {
        const node = nodeById.get(row.current_node_id as string);
        if (!node) continue;
        const family = row.family as MovementFamily;
        const movementRow = bwMovementBySlug.get(node.nodeKey);
        const cleanRepHistory = Array.isArray(row.clean_rep_history)
          ? (row.clean_rep_history as ReadonlyArray<{ reps?: number; seconds?: number }>)
          : [];
        bwByFamily.set(family, {
          family,
          node,
          // Fallback: when the catalog has no row matching the node_key
          // we still need a uuid for movementId — borrow the node's own
          // id, which is rejected by `movement-grouping` only if it
          // collides with a real movements row (it doesn't — disjoint
          // tables). The focus view reads displayName off the item, not
          // the movements row, so the rendered name stays correct.
          movementId: movementRow?.id ?? node.id,
          movementSlug: (movementRow?.slug as string | undefined) ?? node.nodeKey,
          movementName:
            (movementRow?.display_name as string | undefined) ?? node.displayName,
          cleanRepHistory,
          candidateNextNodes: childrenByCurrentId.get(node.id) ?? [],
        });
      }
    }
  }
  const bwHasAnyFamily = bwByFamily.size > 0;

  const userTier = declaredExperienceToTier(experience);
  const resolved = new Map<string, { movementId: string; slug: string; displayName: string }>();
  // ADR 0004 — parallel map keyed by daySlotKey for dual-main-lift secondaries.
  const resolvedSecondary = new Map<string, { movementId: string; slug: string; displayName: string }>();
  const missingRoles: string[] = [];

  for (const day of activeDays) {
    if (day.kind !== "strength") continue;
    let chosen = pickStrengthMovementForBand({
      candidateSlugs: day.candidateSlugs,
      movementBySlug,
      tmMovementIds: new Set(tmByMovementId.keys()),
      tier: userTier,
    });
    // Out-of-band fallback: if the user has TMs but ONLY for movements
    // outside their declared band, honour the TM rather than blocking
    // them from training. They explicitly entered it.
    if (!chosen) {
      for (const slug of day.candidateSlugs) {
        const mv = movementBySlug.get(slug);
        if (mv && tmByMovementId.has(mv.id)) {
          if (process.env.NODE_ENV !== "production") {
            console.warn(
              `[planner] using out-of-band TM ${slug} for tier ${userTier ?? "null"} (band ${mv.experience_min}..${mv.experience_max})`,
            );
          }
          chosen = { movementId: mv.id, slug: mv.slug, displayName: mv.display_name };
          break;
        }
      }
    }
    // Fallback for the no-TM path: use the first available candidate
    // movement purely as a catalog reference. The day will be built
    // accessory-only below (no %TM items), so this is only used so the
    // row has a valid movement_id to attach the prescription to.
    if (!chosen && !hasAnyTm) {
      // Honour the tier here too — first in-band candidate, fall back
      // to first candidate of any tier.
      for (const slug of day.candidateSlugs) {
        const mv = movementBySlug.get(slug);
        if (
          mv &&
          tierInBand(userTier, mv.experience_min ?? 0, mv.experience_max ?? 4)
        ) {
          chosen = { movementId: mv.id, slug: mv.slug, displayName: mv.display_name };
          break;
        }
      }
      if (!chosen) {
        for (const slug of day.candidateSlugs) {
          const mv = movementBySlug.get(slug);
          if (mv) {
            chosen = { movementId: mv.id, slug: mv.slug, displayName: mv.display_name };
            break;
          }
        }
      }
    }
    if (chosen) resolved.set(daySlotKey(day), chosen);
    else missingRoles.push(STRENGTH_ROLE_LABELS[day.role]);

    // ADR 0004 — dual-main-lift secondary resolution. Secondary slot
    // is required (not opt-in): if the day declares a secondaryRole,
    // a TM-backed secondary movement MUST resolve or the user gets
    // the same actionable error as a missing primary TM. Otherwise
    // the user silently loses the entire upper-body maintenance dose
    // that is the whole point of ADR 0004.
    if (day.secondaryCandidateSlugs && day.secondaryCandidateSlugs.length > 0) {
      const secondary = pickSecondaryStrengthMovement({
        candidateSlugs: day.secondaryCandidateSlugs,
        movementBySlug,
        tmMovementIds: new Set(tmByMovementId.keys()),
        tier: userTier,
      });
      if (secondary) {
        resolvedSecondary.set(daySlotKey(day), secondary);
      } else if (day.secondaryRole) {
        missingRoles.push(STRENGTH_ROLE_LABELS[day.secondaryRole]);
      }
    }
  }

  if (missingRoles.length > 0 && hasAnyTm) {
    return {
      ok: false,
      error: `No TM set for: ${missingRoles.join(", ")}. Go to Settings → Training maxes and add one for each.`,
    };
  }

  // Read profile-level limitations once for the whole block — picker
  // honours `blockedRegions` + `tendinopathyActive` on every day.
  const limitationsContext = await readLimitationsContext(supabase, user.id);

  // Migration 0079 — elbow/forearm ATL ratio for the forearm
  // tendon-gate. Computed once per block-generation so we don't
  // re-query for every session. Fails open to 1.0 (no spike) when
  // history is missing.
  const userTimezoneForBlock = await getUserTimezone(user.id);
  const elbowForearmAtlRatio = parsed.data.focusMuscles.includes("forearms")
    ? await getElbowForearmAtlRatio(supabase, user.id, userTimezoneForBlock)
    : 1.0;

  // ADR 0012 — previous-block accessory recency, grouped by day-role, for
  // value-weighted block rotation. Read BEFORE the archive below so the
  // "most recent block" is the one we're about to archive. Only loaded
  // when the archetype actually runs the dynamic picker; empty otherwise
  // (and for a user's first-ever block) → byte-identical to pre-ADR-0012.
  const recencyByRole = archetype.accessoryProfile
    ? await getPreviousBlockAccessoryIdsByRole(supabase, user.id)
    : new Map<string, Set<string>>();
  const EMPTY_RECENCY: Set<string> = new Set();

  const archNow = new Date().toISOString();
  const { error: archErr } = await supabase
    .from("training_blocks")
    .update({ status: "archived", archived_at: archNow, ended_at: archNow })
    .eq("user_id", user.id)
    .eq("status", "active");
  if (archErr) return { ok: false, error: `Couldn't archive prior block: ${archErr.message}` };

  const { data: block, error: blockErr } = await supabase
    .from("training_blocks")
    .insert({
      user_id: user.id,
      archetype: archetype.id,
      started_on: parsed.data.startedOn,
      weeks: archetype.weeks,
      status: "active",
      days_per_week: parsed.data.daysPerWeek,
      day_index_overrides: dayIndexOverrides,
      power_emphasis: parsed.data.powerEmphasis,
      focus_muscles: parsed.data.focusMuscles,
      cardio_source: parsed.data.cardioSource,
      cardio_source_name: parsed.data.cardioSourceName,
      notes: hasAnyTm
        ? null
        : bwHasAnyFamily
          ? "Bodyweight block — main lifts prescribed from your assessed skill nodes."
          : "Bodyweight-only block — main-lift progression coming soon. Accessories programmed per RPE/RIR.",
    })
    .select("id")
    .single();

  if (blockErr || !block) {
    return { ok: false, error: blockErr?.message ?? "Failed to create block" };
  }

  const rows: PlannedSessionInsertRow[] = [];
  for (let week = 0; week < archetype.weeks; week++) {
    const weekProfile = archetype.weekProfiles.find((w) => w.weekIndex === week);
    const weekDeloadScale = weekProfile?.strengthVolumeScale ?? 1.0;
    const weekContext: WeekContextItem[] = [];
    for (const day of activeDays) {
      let movement: { id: string; slug: string; displayName: string };
      let finisherMovement: { id: string; slug: string; displayName: string } | undefined;
      let secondaryMovement: { id: string; slug: string; displayName: string } | undefined;

      if (day.kind === "strength") {
        const resolvedMv = resolved.get(daySlotKey(day));
        if (!resolvedMv) continue;
        movement = { id: resolvedMv.movementId, slug: resolvedMv.slug, displayName: resolvedMv.displayName };
        // ADR 0004 — dual-main-lift secondary movement, when resolved.
        const resolvedSec = resolvedSecondary.get(daySlotKey(day));
        if (resolvedSec) {
          secondaryMovement = {
            id: resolvedSec.movementId,
            slug: resolvedSec.slug,
            displayName: resolvedSec.displayName,
          };
        }
      } else if (day.kind === "cardio") {
        // PR W2 — surface D. When the cardio day declares per-tier
        // alternates, resolve to the user-tier-appropriate slug before
        // looking the movement up in the catalog. Falls back to the
        // default slug for tiers absent from the map.
        const cardioSlug = resolveCardioSlugForTier(day, userTier);
        const mv = movementBySlug.get(cardioSlug);
        if (!mv) continue;
        movement = { id: mv.id, slug: mv.slug, displayName: mv.display_name };
        if (day.finisher) {
          const fin = movementBySlug.get(day.finisher.movementSlug);
          if (fin) finisherMovement = { id: fin.id, slug: fin.slug, displayName: fin.display_name };
        }
      } else {
        // tendon
        const mv = movementBySlug.get(day.movementSlug);
        if (!mv) continue;
        movement = { id: mv.id, slug: mv.slug, displayName: mv.display_name };
      }

      const items =
        day.kind === "cardio" && parsed.data.cardioSource === "external"
          ? buildExternalCardioItems(parsed.data.cardioSourceName)
          : assemblePrescriptionItems(
              archetype,
              week,
              day,
              movement,
              finisherMovement,
              movementBySlug,
              pickerCatalog,
              weekContext,
              weekDeloadScale,
              parsed.data.powerEmphasis,
              warmupScheme,
              equipment,
              // Omit the barbell strength path when the user has no loadable
              // kit. This makes equipment the source of truth — TMs persist
              // across blocks, but the BW preset gives a bodyweight-only block
              // even if barbell TMs are saved from a previous block.
              bwActive || !hasAnyTm,
              experience,
              limitationsContext,
              secondaryMovement,
              parsed.data.focusMuscles,
              elbowForearmAtlRatio,
              day.role ? (recencyByRole.get(day.role) ?? EMPTY_RECENCY) : EMPTY_RECENCY,
            );

      // ─── Bodyweight Phase 3 — prepend BW main + back_off items ───
      // Only on strength days, only when the user has bw_progress rows
      // populated AND has no loadable kit. The matrix runs against the
      // user's current node per family; the rotation seeds off (block,
      // day, slot) so consecutive sessions don't double-stack the same
      // patterns. Pad weekIndex into the matrix's expected 0..3 domain
      // for blocks longer than 4 weeks.
      if (day.kind === "strength" && bwActive && bwHasAnyFamily) {
        const wIdx = (Math.max(0, Math.min(3, week)) as 0 | 1 | 2 | 3);
        const seed = `${block.id}:${day.dayIndex}:${day.slot ?? "single"}`;
        const userBodyweightKg = profile?.bodyweight_kg != null
          ? Number(profile.bodyweight_kg)
          : undefined;
        const bwItems = buildBwMainItemsForSession({
          byFamily: bwByFamily,
          archetype: archetype.id,
          weekIndex: wIdx,
          seed,
          equipment,
          userBodyweightKg: Number.isFinite(userBodyweightKg as number)
            ? (userBodyweightKg as number)
            : undefined,
        });
        // Prepend so BW mains come before accessories (mirrors the
        // legacy main → accessory ordering on the barbell path).
        items.unshift(...bwItems);
      }

      // ─── Phase 5 — modality classifier ───
      // Stamped on every planned session (including legacy / non-BW
      // blocks). The ceiling engine consumes `effective_stress_load`
      // when aggregating; the UI renders a small chip off
      // `session_modality`.
      const classification = classifyPlannedSession(items, archetype.id);

      // ─── Phase 5 — hinge compensation ───
      // BW-only sessions where the family rotation didn't land on
      // `hinge` AND the user has acknowledged the gap (assessment
      // completed) get a slow-tempo / eccentric / isometric hinge
      // movement appended near the end of the session.
      //
      // Gates (in order):
      //   - equipment.preset === "bodyweight_only"
      //   - day.kind === "strength" (don't inject on cardio / tendon)
      //   - profile.bw_assessment_completed_at IS NOT NULL
      //   - the BW main-lift block didn't already cover hinge
      //   - maybeInjectHingeCompensation says inject (recovery-day +
      //     no-progress-state branches short-circuit inside)
      //
      // The injected item is bucket=accessory and carries a
      // `meta.hinge_compensation` flag so settings / audit consumers
      // can find it without re-deriving from the node key.
      const bwOnly = equipment.preset === "bodyweight_only";
      const assessmentCompleted = Boolean(profile?.bw_assessment_completed_at);
      if (
        bwOnly &&
        day.kind === "strength" &&
        assessmentCompleted
      ) {
        const hingeAlreadyCovered = items.some(
          (it) => it.bw?.family === "hinge",
        );
        if (!hingeAlreadyCovered) {
          const hingeCtx = bwByFamily.get("hinge");
          const hingeProgress: BwProgress | null = hingeCtx
            ? ({
                userId: user.id,
                family: "hinge",
                currentNodeId: hingeCtx.node.id,
                accumulatedTutSeconds: 0,
                weeksAtNode: 0,
                cleanRepHistory: [],
                targetExternalLoadKg: null,
                updatedAt: new Date(),
              } as BwProgress)
            : null;
          const decision = maybeInjectHingeCompensation({
            bwProgress: hingeProgress,
            currentNode: hingeCtx?.node ?? null,
            plannedSession: {
              hasHingeMovement: false,
              sessionModality: classification.modality,
              weekIndex: (Math.max(0, Math.min(3, week)) as 0 | 1 | 2 | 3),
            },
          });
          if (decision.inject && decision.movement && hingeCtx) {
            items.push(
              buildHingeCompensationItem({
                movementId: hingeCtx.movementId,
                nodeKey: decision.movement.nodeKey,
                prescription: decision.movement,
                displayName: hingeCtx.node.displayName,
              }),
            );
          }
        }
      }
      const prescription: Prescription = { items };
      const isDeload = weekProfile?.intensityLabel === "Deload";

      let title = day.title;
      if (day.kind === "strength") {
        // When the BW path is the source of truth for this session,
        // derive the title from the first BW main movement so the day
        // card header reads "Wall handstand hold" / "Push-up" — not the
        // barbell day-template label that no longer applies. Falls
        // through to the barbell title only when the barbell path
        // actually generated items.
        const firstBwMain = bwActive
          ? items.find((it) => it.kind === "main")
          : undefined;
        if (firstBwMain) {
          const name = firstBwMain.movementName ?? movement.displayName;
          title = `${name}${isDeload ? " (deload)" : ""}`;
        } else if (hasAnyTm && !bwActive) {
          title = `${movement.displayName}${isDeload ? " (deload)" : ""}`;
        } else if (isDeload) {
          title = `${day.title} (deload)`;
        }
      } else if (isDeload) {
        title = `${day.title} (deload)`;
      }

      rows.push({
        block_id: block.id,
        user_id: user.id,
        week_index: week,
        day_index: day.dayIndex,
        slot: sanitiseSlotForMode(day.slot, allowsTwoADays),
        title,
        role: day.role,
        prescription,
        session_modality: classification.modality,
        effective_stress_load: classification.load,
      });
    }
  }

  const { error: psErr } = await supabase.from("planned_sessions").insert(rows);
  if (psErr) {
    // Roll back the block we just created so we don't leave a zombie.
    await supabase.from("training_blocks").delete().eq("id", block.id);
    return { ok: false, error: `Couldn't create planned sessions: ${psErr.message}` };
  }

  revalidatePath("/app");
  revalidatePath("/app/plan");
  revalidatePath("/app/stats");
  // Bodyweight Phase 6 — capture a diagnostics snapshot now that the
  // block's planned sessions exist (drift detection reads the
  // planner items via `planned_sessions`, so the post-creation
  // shape is the one we want frozen). Non-blocking.
  try {
    const { captureBwDiagnosticsSnapshot } = await import(
      "@/lib/planner/bw-diagnostics-snapshot"
    );
    await captureBwDiagnosticsSnapshot({ supabase, userId: user.id });
  } catch (e) {
    console.error("captureBwDiagnosticsSnapshot (createBlock) failed:", e);
  }
  return { ok: true };
}


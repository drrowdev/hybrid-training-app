/**
 * Movement-row shape used by the main-lift resolver. Only the columns
 * actually read at the call site — the resolver doesn't need the full
 * `DbMovement` projection (no muscles / roles / scores).
 */
type StrengthMovementRow = {
  id: string;
  slug: string;
  display_name: string;
  experience_min: number | null;
  experience_max: number | null;
};

/**
 * PR W2 — pick the first candidate slug whose movement falls within
 * the user's experience band AND has a TM logged. Encodes Surface B
 * (main-lift resolver) so a user with TMs for `[back-squat-high-bar,
 * pause-back-squat]` picks the high-bar at tier 0 and the pause variant
 * only when the band allows it. Tier `null` (no declaration) preserves
 * the legacy "first candidate with a TM" behaviour.
 *
 * Returns `null` if no in-band candidate has a TM — caller handles the
 * out-of-band fallback (use the TM anyway, log a dev warning) so the
 * filter doesn't block training.
 */
function pickStrengthMovementForBand({
  candidateSlugs,
  movementBySlug,
  tmMovementIds,
  tier,
}: {
  candidateSlugs: readonly string[];
  movementBySlug: Map<string, StrengthMovementRow>;
  tmMovementIds: Set<string>;
  tier: number | null;
}): { movementId: string; slug: string; displayName: string } | null {
  for (const slug of candidateSlugs) {
    const mv = movementBySlug.get(slug);
    if (!mv) continue;
    if (!tmMovementIds.has(mv.id)) continue;
    if (!tierInBand(tier, mv.experience_min ?? 0, mv.experience_max ?? 4)) continue;
    return { movementId: mv.id, slug: mv.slug, displayName: mv.display_name };
  }
  return null;
}

/**
 * ADR 0004 — resolve the dual-main-lift secondary movement for a strength
 * day that declares `secondaryCandidateSlugs`. Mirrors the in-band-with-TM
 * → out-of-band-TM fallback used for the primary slot, BUT does **not**
 * fall back to a no-TM catalog reference: if no TM is set anywhere in the
 * secondary candidate list, this returns null and the prescription emits
 * the primary lift only. The secondary slot is opt-in via TM.
 */
function pickSecondaryStrengthMovement({
  candidateSlugs,
  movementBySlug,
  tmMovementIds,
  tier,
}: {
  candidateSlugs: readonly string[];
  movementBySlug: Map<string, StrengthMovementRow>;
  tmMovementIds: Set<string>;
  tier: number | null;
}): { movementId: string; slug: string; displayName: string } | null {
  const inBand = pickStrengthMovementForBand({ candidateSlugs, movementBySlug, tmMovementIds, tier });
  if (inBand) return inBand;
  for (const slug of candidateSlugs) {
    const mv = movementBySlug.get(slug);
    if (mv && tmMovementIds.has(mv.id)) {
      return { movementId: mv.id, slug: mv.slug, displayName: mv.display_name };
    }
  }
  return null;
}

/**
 * Whitelist the 5 declared experience tiers shipped in migration 0052.
 * Anything else (null, legacy values, undeclared) collapses to null so
 * the accessory picker treats the user as "not declared" and keeps the
 * pre-PR-W1 behaviour (no filtering).
 */
const DECLARED_EXPERIENCE_VALUES: ReadonlySet<DeclaredExperience> = new Set([
  "beginner_lt_6m",
  "novice_6m_2y",
  "intermediate_2y_5y",
  "advanced_5y_10y",
  "highly_advanced_10y_plus",
]);

function resolveDeclaredExperience(
  raw: string | null | undefined,
): DeclaredExperience | null {
  if (!raw) return null;
  return DECLARED_EXPERIENCE_VALUES.has(raw as DeclaredExperience)
    ? (raw as DeclaredExperience)
    : null;
}

// ─── Phase 5 — modality classifier + stress-load helpers ─────────────

/**
 * Map a curated CardioDay's `cardioKind` to the classifier's mode tag.
 * The classifier only distinguishes Z2 / HIIT / mixed; finer-grained
 * shapes (alactic vs threshold vs VO2) collapse into HIIT or mixed
 * because they hit the same recovery-cost branch.
 */
function cardioModeFor(
  kind: PrescriptionItem["kind"],
): "z2" | "hiit" | "mixed" {
  if (kind === "cardio_z2") return "z2";
  if (kind === "cardio_alactic" || kind === "cardio_vo2") return "hiit";
  if (kind === "cardio_threshold") return "mixed";
  return "mixed";
}

/**
 * Convert the planned-session prescription `items` array (the same
 * shape that gets serialised onto `planned_sessions.prescription`)
 * into the classifier's input contract.
 *
 * Strength items map by `kind`:
 *   - main → bucket=main
 *   - back_off → bucket=back_off
 *   - accessory / tendon / power_potentiation → bucket=accessory
 *   - warmup → kind=warmup (the classifier ignores these)
 *
 * Cardio items emit a single `cardioBlock` carrying `durationMinutes`.
 * `estimatedHardSets` for cardio is set to 0 — the multiplier covers
 * the recovery cost, the hard-set count is for strength work.
 */
function itemsToClassifierMovements(
  items: ReadonlyArray<PrescriptionItem>,
  archetype: ArchetypeId,
): ClassifierMovement[] {
  const out: ClassifierMovement[] = [];
  for (const it of items) {
    if (it.kind === "warmup") {
      out.push({ kind: "warmup", archetype, estimatedHardSets: 0 });
      continue;
    }
    if (
      it.kind === "cardio_z2" ||
      it.kind === "cardio_alactic" ||
      it.kind === "cardio_vo2" ||
      it.kind === "cardio_threshold" ||
      it.kind === "cardio_external"
    ) {
      out.push({
        kind: "conditioning",
        archetype,
        cardioBlock: {
          // External cardio collapses to z2 for stress-budget purposes:
          // the user is following an outside program so we can't know
          // the actual intensity. Z2 is the safest default — the
          // multiplier under-counts hard runs (acceptable) instead of
          // over-counting easy ones (would suppress strength volume).
          mode: it.kind === "cardio_external" ? "z2" : cardioModeFor(it.kind),
          // Phase 1 — external blocks carry no `durationMin`. 0 lets the
          // calendar / modality classifier still register a cardio day
          // without inflating effective_stress_load against unknown work.
          durationMinutes: it.durationMin ?? 0,
        },
        estimatedHardSets: 0,
      });
      continue;
    }
    const sets = Math.max(0, it.sets ?? 1);
    if (it.kind === "main") {
      out.push({
        kind: "main",
        archetype,
        bucket: "main",
        estimatedHardSets: sets,
        bw: it.bw
          ? {
              prescriptionType: it.bw.prescriptionType,
              family: (it.bw.family as MovementFamily | undefined) ?? "push_h",
              nodeDifficulty: 0,
            }
          : undefined,
      });
      continue;
    }
    if (it.kind === "back_off") {
      out.push({
        kind: "back_off",
        archetype,
        bucket: "back_off",
        estimatedHardSets: sets,
      });
      continue;
    }
    // accessory / tendon / power_potentiation
    out.push({
      kind: "accessory",
      archetype,
      bucket: "accessory",
      estimatedHardSets: sets,
    });
  }
  return out;
}

/**
 * Stamp the modality + effective-stress-load on a planned session.
 * Centralised so createBlock and createCustomBlock produce the same
 * shape — they're the only two callers that build planner rows.
 */
function classifyPlannedSession(
  items: ReadonlyArray<PrescriptionItem>,
  archetype: ArchetypeId,
): { modality: SessionModality; load: number } {
  const movs = itemsToClassifierMovements(items, archetype);
  const modality = classifySessionModality({ movements: movs });
  const hardSets = movs.reduce(
    (acc, m) => acc + (m.kind === "warmup" ? 0 : Math.max(0, m.estimatedHardSets)),
    0,
  );
  const load = effectiveStressLoad({ modality, hardSets });
  return { modality, load };
}

/**
 * Build the prescription-item shape for an injected hinge-compensation
 * movement. The injected item is bucketed as `accessory` so existing
 * focus-view / logging paths render it without special-casing; the
 * `meta.hinge_compensation` flag distinguishes it from a normal
 * accessory pick for downstream consumers (settings page, audit).
 */
function buildHingeCompensationItem(args: {
  movementId: string;
  nodeKey: string;
  prescription: {
    nodeKey: string;
    prescriptionType: "isometric_hold" | "tempo_reps" | "reps";
    sets: number;
    reps?: number;
    holdSeconds?: number;
    tempoEccentricSec: number;
    targetRir: number;
    intensityCue: string;
  };
  displayName: string;
}): PrescriptionItem {
  const p = args.prescription;
  const item: PrescriptionItem = {
    movementId: args.movementId,
    movementSlug: p.nodeKey,
    movementName: args.displayName,
    kind: "accessory",
    sets: p.sets,
    targetRir: { min: p.targetRir, max: p.targetRir },
    tempoEccentricSec: p.tempoEccentricSec,
    intensityCue: p.intensityCue,
    intensityLabel: "hinge compensation",
    notes:
      "Posterior-chain compensation — your session didn't include a hinge pattern.",
    bw: {
      prescriptionType: p.prescriptionType,
      sets: p.sets,
      reps: p.reps,
      holdSeconds: p.holdSeconds,
      tempoEccentricSec: p.tempoEccentricSec,
      targetRir: p.targetRir,
      restSeconds: 90,
      intensityCue: p.intensityCue,
      nodeKey: p.nodeKey,
      nodeDisplayName: args.displayName,
      family: HINGE_COMPENSATION_FAMILY,
    },
    meta: { hinge_compensation: true, hinge_compensation_node: p.nodeKey },
  };
  if (p.prescriptionType === "isometric_hold" && p.holdSeconds != null) {
    item.holdSec = { min: p.holdSeconds, max: p.holdSeconds };
  } else if (p.reps != null) {
    item.reps = p.reps;
  }
  return item;
}

